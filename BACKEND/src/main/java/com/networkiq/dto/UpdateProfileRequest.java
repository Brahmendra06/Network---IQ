package com.networkiq.dto;

public class UpdateProfileRequest {

    private Long id;
    private String name;

    public UpdateProfileRequest() {
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

}